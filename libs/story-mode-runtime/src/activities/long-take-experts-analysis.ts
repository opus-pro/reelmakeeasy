export function normalizeLongTakeAssetManagerOutput(params: {
  manifest: LongTakeAssetManifestOutput
  modelOutput: LongTakeAssetManagerModelOutput
}): LongTakeAssetManagerOutput {
  const manifestById = new Map(params.manifest.asset_manifest.map((item) => [item.asset_id, item]))
  const prompts: LongTakeAssetManagerOutput['prompts'] = []

  for (const item of params.modelOutput.prompts) {
    const assetId = normalizeRequiredText(item.asset_id)
    const promptText = normalizeRequiredText(item.prompt_text)
    if (!assetId || !promptText) {
      continue
    }

    const manifestAsset = manifestById.get(assetId)
    const resolvedSource =
      item.source === 'USER_FILE' || manifestAsset?.source === 'USER_FILE' ? 'USER_FILE' : null
    const normalizedType = normalizePromptAssetType(
      item.type,
      manifestAsset?.type,
      assetId,
      resolvedSource,
    )
    if (!normalizedType) {
      continue
    }

    prompts.push({
      asset_id: assetId,
      header: normalizeText(item.header),
      layout_block:
        normalizeRequiredText(item.layout_block) || LONG_TAKE_ASSET_MANAGER_LAYOUT_BLOCK,
      prompt_text: promptText,
      shot_list: uniqueStrings(item.shot_list),
      source: resolvedSource,
      type: normalizedType,
    })
  }

  return { prompts }
}

export function normalizeLongTakeAssetManifestOutput(params: {
  modelOutput: LongTakeAssetManifestModelOutput
  strictUserFileBinding?: boolean
  validFileIds?: Set<string>
}): LongTakeAssetManifestOutput {
  const { strictUserFileBinding = false, validFileIds } = params
  const manifest: LongTakeAssetManifestOutput['asset_manifest'] = []

  for (const item of params.modelOutput.asset_manifest) {
    const type = normalizeAssetType(item.type, item.asset_id)
    // Filter out Sets - they never get anchor images generated
    if (type === 'Set') {
      continue
    }
    const keyword = normalizeRequiredText(item.keyword)
    if (!keyword) {
      continue
    }
    const visualTag = normalizeRequiredText(item.visual_tag)
    const visualReference = normalizeRequiredText(item.visual_reference)
    const baseAssetId = normalizeRequiredText(item.asset_id)
    const normalizedAssetId = normalizeAssetId({
      assetId: baseAssetId,
      index: manifest.length,
      keyword,
      type,
    })
    const normalizedSource = item.source === 'USER_FILE' ? 'USER_FILE' : null
    const normalizedSourceFileId = normalizeText(item.source_file_id)
    const isValidSourceFileId =
      normalizedSourceFileId && (!validFileIds || validFileIds.has(normalizedSourceFileId))

    if (strictUserFileBinding && normalizedSource === 'USER_FILE' && !isValidSourceFileId) {
      throw new Error(
        `[long-take] Invalid source_file_id for USER_FILE asset ${normalizedAssetId || '<unknown>'}`,
      )
    }

    const source = normalizedSource === 'USER_FILE' && isValidSourceFileId ? 'USER_FILE' : null
    const sourceFileId =
      normalizedSource === 'USER_FILE' && isValidSourceFileId ? normalizedSourceFileId : null

    manifest.push({
      asset_id: normalizedAssetId,
      ...(item.is_multi_angle && { is_multi_angle: true }),
      keyword,
      proper_name: normalizeText(item.proper_name),
      source,
      source_file_id: sourceFileId,
      // Forward the planner-decided passthrough flag verbatim. Without
      // this, `buildAnchorAssetTaskItem`'s manifest-first lookup always
      // falls through to the filename heuristic and UIP-tagged
      // passthroughs that don't match `isLogoAssetShortname` get
      // regenerated as styled cartoon variants.
      ...(item.source_passthrough && { source_passthrough: true }),
      type: type as 'Character' | 'Prop',
      visual_reference: visualReference,
      visual_tag: visualTag,
    })
  }

  return { asset_manifest: manifest }
}

export function normalizeLongTakeBeatSheetOutput(params: {
  auditPassed?: boolean
  correctedTimeRanges?: Array<null | { end: number; start: number }>
  // Keep beats whose segment_text is empty instead of dropping them. The music-video route builds a
  // deterministic beat sheet whose instrumental beats (intro / interlude / outro) carry an empty
  // segment_text on purpose; dropping them would leave those instrumental sections with no shots and
  // a silent gap before the first lyric. Text/UIP routes keep the default (drop empties).
  keepEmptySegments?: boolean
  modelOutput: LongTakeBeatSheetModelOutput
  textAudited?: boolean
}): LongTakeBeatSheetOutput {
  const {
    auditPassed = false,
    correctedTimeRanges,
    keepEmptySegments = false,
    textAudited = false,
  } = params
  const beats: LongTakeBeatSheetOutput['beat_sheet'] = []

  for (const item of params.modelOutput.beat_sheet) {
    const segmentText = item.segment_text.trim()
    if (!segmentText && !keepEmptySegments) {
      continue
    }

    const beat: LongTakeBeatSheetOutput['beat_sheet'][number] = {
      beat_id: beats.length + 1,
      segment_text: segmentText,
    }

    if (auditPassed || textAudited) {
      // Write time_range whenever text is audited (textOk=true), since correctedTimeRanges
      // are derived from transcript and are accurate regardless of timeOk.
      // Falls back to item.time_range when reading back from storage (no correctedTimeRanges).
      const corrected = correctedTimeRanges?.[beats.length]
      const timeRange = corrected ?? item.time_range ?? null
      if (timeRange) {
        beat.time_range = { start: timeRange.start, end: timeRange.end }
        beat.duration = timeRange.end - timeRange.start
      }
    }

    beats.push(beat)
  }

  const output: LongTakeBeatSheetOutput = { beat_sheet: beats }
  if (auditPassed) {
    output.time_range_audited = true
    output.text_audited = true
  } else if (textAudited) {
    output.text_audited = true
  }
  return output
}

