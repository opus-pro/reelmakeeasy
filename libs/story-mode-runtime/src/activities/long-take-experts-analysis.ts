export function resolveLongTakeDirectorId(value: unknown): LongTakeDirectorId {
  const parsed = LongTakeDirectorIdSchema.safeParse(value)
  return parsed.success ? parsed.data : LONG_TAKE_DEFAULT_DIRECTOR_ID
}

function auditNormalizeToken(token: string): string {
  return token
    .toLowerCase()
    .replace(/[\u2019']/g, '')
    .replace(/[^\p{L}\p{N}]+/gu, '')
}

function normalizeAssetId(params: {
  assetId: string
  index: number
  keyword: string
  type: 'Character' | 'Prop' | 'Set'
}): string {
  const { assetId, index, keyword, type } = params
  const normalized = assetId.trim().toLowerCase()
  if (normalized) {
    return normalized
  }

  const prefix = type === 'Character' ? 'char' : type === 'Set' ? 'set' : 'prop'
  const slug = slugify(keyword) || `${prefix}_${index + 1}`
  return slug.startsWith(`${prefix}_`) ? slug : `${prefix}_${slug}`
}

function normalizeAssetType(value: string, assetId: string): 'Character' | 'Prop' | 'Set' {
  const normalized = value.trim().toLowerCase()
  if (normalized === 'character') {
    return 'Character'
  }
  if (normalized === 'set') {
    return 'Set'
  }
  if (normalized === 'prop') {
    return 'Prop'
  }

  const normalizedAssetId = assetId.trim().toLowerCase()
  if (normalizedAssetId.startsWith('char_')) {
    return 'Character'
  }
  if (normalizedAssetId.startsWith('set_')) {
    return 'Set'
  }
  return 'Prop'
}

function normalizePromptAssetType(
  promptType: null | string | undefined,
  manifestType: 'Character' | 'Prop' | 'Set' | undefined,
  assetId: string,
  _source: 'USER_FILE' | null,
): 'Character' | 'Prop' | null {
  const normalizedPromptType = promptType?.trim().toLowerCase()
  if (normalizedPromptType === 'character') {
    return 'Character'
  }
  if (normalizedPromptType === 'prop') {
    return 'Prop'
  }
  // Sets are never eligible for anchor image generation
  if (normalizedPromptType === 'set') {
    return null
  }

  if (manifestType === 'Character') {
    return 'Character'
  }
  if (manifestType === 'Prop') {
    return 'Prop'
  }
  if (manifestType === 'Set') {
    return null
  }

  const normalizedAssetId = assetId.toLowerCase()
  if (normalizedAssetId.startsWith('char_')) {
    return 'Character'
  }
  if (normalizedAssetId.startsWith('set_')) {
    return null
  }
  return 'Prop'
}

function normalizeRequiredText(value: null | string | undefined): string {
  return value?.trim() || ''
}

function normalizeText(value: null | string | undefined): null | string {
  const trimmed = value?.trim()
  return trimmed ? trimmed : null
}

function scanBeatTokens(
  beatTokens: string[],
  transcriptWords: Array<{ end: number; start: number; word: string }>,
  txCursor: number,
): { firstTxIdx: number; lastTxIdx: number; mismatchCount: number; nextCursor: number } {
  let firstTxIdx = -1
  let lastTxIdx = -1
  let mismatchCount = 0
  let cursor = txCursor

  for (const token of beatTokens) {
    if (cursor >= transcriptWords.length) {
      mismatchCount++
      continue
    }
    const txToken = auditNormalizeToken(transcriptWords[cursor].word)
    if (txToken === token) {
      if (firstTxIdx === -1) {
        firstTxIdx = cursor
      }
      lastTxIdx = cursor
      cursor++
    } else {
      mismatchCount++
      cursor++
    }
  }

  return { firstTxIdx, lastTxIdx, mismatchCount, nextCursor: cursor }
}

function slugify(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9_ -]/g, '')
    .replace(/\s+/g, '_')
    .replace(/-+/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '')
}

function uniqueStrings(values: string[]): string[] {
  return Array.from(new Set(values.map((value) => value.trim()).filter(Boolean)))
}
