/**
 * This file contains the types for the new refine v2
 *
 * Clips - Tracks - Sections - Segments
 * Segment: Frame + Duration + Position + Content + PropertiesMap
 */
import {
  AnalysisResultType,
  CaptionColorType,
  KeyFrameLayoutType,
  KeyFrameResourceType,
  MovingSpeakerType,
  PlayMode,
  TrackingType,
} from '../enums/refine-v2.enum'

/**
 * AnalysisResultMap is designed to carry the source of truth.
 *
 * The source of truth is the analysis results of the CV models,
 * not the business logic derived from the analysis result.
 * For example, positions of three faces is source of truth,
 * but the layout type "Three" is not source of truth.
 *
 * Note:
 * All new added result types should be marked as optional(?:),
 * this is for backward compatibility and to enable auto lint.
 */
type AnalysisResultMap = {
  [AnalysisResultType.ActiveSpeaker]: boolean
  [AnalysisResultType.Face]: CenterPercentageAreaPosition[]
  [AnalysisResultType.FaceV2]?: FaceV2[]
  [AnalysisResultType.FakeFace]: number[]
  [AnalysisResultType.FakeFaceCrops]?: CenterPercentageAreaPosition[]
  [AnalysisResultType.Grid]?: Grid
  [AnalysisResultType.MovingSpeaker]: MovingSpeakerType
  [AnalysisResultType.People]: CenterPercentageAreaPosition[]
  [AnalysisResultType.PeopleV2]?: PeopleV2[]
  [AnalysisResultType.Screen]: CenterPercentageAreaPosition[]
  [AnalysisResultType.TrackingSubjects]?: TrackingSubjectMap
}

// FIXME: import it from types/core/engine-legacy
type AreaPositionBase = {
  type: PositionType
}

/**
 * This is a data structure to mark the bundled data in editingScript
 * By design, Bundled items are of the same level (track, section, segment)
 */
export type CaptionContent = ContentBase & {
  scale?: number
  speakerId?: string
  // Adjustable properties
  textElements: TextElement[]
}
export type CaptionSegment = UniversalSegment<
  TimeStampDuration,
  CenterPercentageAreaPosition,
  CaptionContent
>
export type CaptionTrack = UniversalTrack<
  TimeStampDuration,
  CenterPercentageAreaPosition,
  CaptionContent
> & {
  sections: UniversalSection<TimeStampDuration, CenterPercentageAreaPosition, CaptionContent>[]
  trackType: 'CaptionTrack'
}

/***************************************
 * Editor2.2(Animation & Text Overlay) *
 ***************************************/

// FIXME: import it from types/core/engine-legacy
type CenterPercentageAreaPosition = AreaPositionBase & {
  defaultRatioType?: DefaultRatioType
  /**
   * vertical dimension of the bounding box, divided by
   * the height of the canvas, ranged within [0, 1]
   */
  hPct: number
  /**
   * horizontal dimension of the bounding box, divided by
   * the width of the canvas, ranged within [0, 1]
   */
  wPct: number
  /**
   * horizontal distance between the center of the
   * bounding box and center of the canvas,
   * range within [-1, 1]
   */
  xPct: number
  /**
   * vertical distance between the center of the
   * bounding box and center of the canvas,
   * range within [-1, 1]
   */
  yPct: number
}
type ContentBase = {
  duration: TimeStampDuration
  id?: string
  timeline: Timeline
}

/**
 * Content
 */
type ContentType =
  | 'Audio'
  | 'BRoll'
  | 'Caption'
  | 'Emoji'
  | 'KeyFrameGroup'
  | 'KeyFrameInfo'
  | 'Mask'
  | 'Media'
  | 'ScreenOverlay'
  | 'Sound'
  | 'TextOverlay'
  | 'VideoEffect'
  | 'VoiceOver'

/**
 * Area's default ratio type
 * Custom: Any ratios, not fixed
 * Others: fixed ratio
 */
type DefaultRatioType = '1:1' | '4:3' | '4:5' | '9:8' | '9:16' | '16:9' | 'Custom' | 'Original'
type DurationBase = {
  type?: DurationType
}

/**
 * Duration
 */
type DurationType =
  | 'FI' // Frame Index
  | 'TS' // Timestamp

/**
 * FaceV2 carries the source of truce generated by face detection and ASD(Active Speaker
 * Detection) model
 */
type FaceV2 = {
  activeness?: number
  faceness?: number
  id: string
  isFake: boolean
  pos: CenterPercentageAreaPosition
}

/**
 * Segment the frame image into a grid and select the cropping area and layout based on the grid
 * through VLLM Only apply to Fill and Fit layout
 */
export type Grid = {
  cameraViewLayout?: KeyFrameLayoutType.Default | KeyFrameLayoutType.Fill | KeyFrameLayoutType.Fit
  crops: CenterPercentageAreaPosition[]
  layout: KeyFrameLayoutType.Fill | KeyFrameLayoutType.Fit
}
export type KeyFrameTrack = UniversalTrack<
  TimeStampDuration,
  CenterPercentageAreaPosition,
  KeyFrameGroupContent
> & {
  sections: UniversalSection<
    TimeStampDuration,
    CenterPercentageAreaPosition,
    KeyFrameGroupContent
  >[]
  trackType: 'KeyFrameTrack'
}

type KeyFrameContent = ContentBase & {
  // Analysis result
  analysisResult: AnalysisResultMap
  // Adjustable properties
  cropAreaAdjustment?: (CenterPercentageAreaPosition | undefined)[]
  // Crop areas
  cropAreas: CenterPercentageAreaPosition[]
  // There is a layoutType erasing logic in refine-v2.adapter.ts.createKeyFrameGroupContent method,
  // as a result, KeyFrameContent will not have layoutType in the final editing script.
  layoutType?: KeyFrameLayoutType
  mode?: PlayMode
  resourceType?: KeyFrameResourceType
  // Multi resource, if resourceUri is not provided, it means the resource is original video
  resourceUri?: string
  // Rotation angle 0-360
  rotation?: number[]
  targetAreaAdjustment?: CenterPercentageAreaPosition[]
}
type KeyFrameGroupContent = ContentBase & {
  keyFrameContents: KeyFrameContent[]
  layoutType: KeyFrameLayoutType
  layoutTypeAdjustment?: KeyFrameLayoutType
}
/**
 * PeopleV2 carries the source of truce generated by object detection alignment info
 */
type PeopleV2 = {
  // undefined if there is no face aligned with this people
  faceId?: string
  peopleness: number
  pos: CenterPercentageAreaPosition
}

