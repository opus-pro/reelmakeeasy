type PositionType =
  | 'CPct' // CenterPercentage
  | 'CPx' // CenterPixel
  | 'LTPct' // LeftTopPercentage
  | 'LTPx' // LeftTopPixel
type PropertiesValue = boolean | number | number[] | string
type TextAnimation = {
  // TODO 1
  [key: string]: unknown
}

/**
 * CaptionContent
 */
export type TextElement = {
  animation?: TextAnimation
  color: CaptionColorType
  deleted?: boolean
  duration: TimeStampDuration
  id?: string
  text: string
  textAdjustment?: string
  textStyle?: TextStyle
  timeline: Timeline
  type?: 'curse' | 'filler'
}

// Text Overlay
export type TextStyle = {
  backgroundColor?: string
  borderRadius?: number
  fontColor?: string
  fontFamily?: string
  fontSize?: number
  fontStyle?: string
  fontWeight?: string
  // below 4 are for custom font
  id?: string
  italic?: boolean
  letterSpacing?: number
  lineHeight?: number
  name?: string
  path?: string
  textAlign?: string
  textDecoration?: string
  textShadow?: string
  type?: 'CustomizedFont' | 'System'
}

/**
 * Timeline
 * - in: the start time of the current clip (Can be negative for intro)
 * - out: the end time of the current clip
 */
export type Timeline = {
  in: number
  out: number
}
export type TimeStampDuration = DurationBase & {
  eO: number // End Offset Ms

  // For manual adjustment
  eOAdj?: number

  sO: number // Start Offset Ms

  // For manual adjustment
  sOAdj?: number
}

/**
 * TrackingSubjectMap carries the source of truce generated by tracking model
 * key - id of the tracking subject
 * value - CenterPercentageAreaPosition
 */
type TrackingSubjectMap = {
  // exists when status = on/off
  selected?: string
  status: TrackingType
  // exists when status = on/off
  value?: {
    [key: string]: TrackingSubjectMapValue
  }
}
type TrackingSubjectMapValue = {
  name: string
  pos: CenterPercentageAreaPosition
}
type TrackType =
  | 'AudioTrack'
  | 'CaptionTrack'
  | 'EmojiTrack'
  | 'KeyFrameTrack'
  | 'MediaTrack'
  | 'ScreenOverlayTrack'
  | 'TextOverlayTrack'
  | 'VideoEffectTrack'
  | 'VoiceEnhancementTrack'
  | 'VoiceOverTrack'
/**
 * Segment
 */
type UniversalSection<
  Duration extends DurationBase,
  Position extends AreaPositionBase,
  Content extends ContentBase,
> = {
  id?: string
  // Reserve for manual adjustment
  propertiesMap?: Record<string, unknown>
  sceneId?: string
  sectionDuration: Duration
  sectionTimeline: Timeline
  segments: UniversalSegment<Duration, Position, Content>[]
}
type UniversalSegment<
  Duration extends DurationBase,
  Position extends AreaPositionBase,
  Content extends ContentBase,
> = {
  content: Content
  contentType: ContentType
  duration: Duration
  id?: string
  position?: Position
  positionAdjustment?: Position
  // Reserve for manual adjustment
  propertiesMap?: Record<string, PropertiesValue>
  timeline: Timeline
}
type UniversalTrack<
  Duration extends DurationBase,
  Position extends AreaPositionBase,
  Content extends ContentBase,
> = {
  category?: string
  // Indicate which kind of track it is
  id?: string
  sections: UniversalSection<Duration, Position, Content>[]
  trackType: TrackType
}
