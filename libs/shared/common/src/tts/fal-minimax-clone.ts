/**
 * MiniMax voice cloning via fal.ai. The endpoint comes from the model
 * registry (`roles["voice.clone"]`, by default `fal-ai/minimax/voice-clone`).
 *
 * The core mechanic: **fal's clone endpoint takes no `voice_id` input at all** and
 * returns its own `custom_voice_id`. Clone ids are tenant-scoped, so a voice minted
 * on MiniMax's own API (a legacy `provider: 'minimax'` row) cannot be synthesized
 * here -- it has to be re-cloned, producing a NEW row (`migratedFromVoiceId`).
 *
 * Payload deltas versus MiniMax's own clone API, all handled here:
 *
 * 1. `noise_reduction` on fal vs `need_noise_reduction` on MiniMax. Same meaning,
 *    different key -- a silent no-op if sent under the wrong name.
 * 2. Input is a public `audio_url`, not an uploaded `file_id`. A local file is
 *    pushed through `fal.storage.upload` first.
 * 3. **No accent/clone-prompt support.** MiniMax accepts a `clone_prompt`
 *    (audio + text) that the app uses via `createMiniMaxAccentPrompt` to improve
 *    accent fidelity. Fal's schema has no equivalent, so a fal-minted clone is
 *    built from the sample alone. Callers must not assume parity here.
 * 4. **No `language_boost`.** MiniMax biases the preview TTS to the detected
 *    language; fal's clone input cannot, so the preview may be read in the wrong
 *    accent for a non-English sample. Only the preview is affected -- real
 *    synthesis still passes `language_boost` through the TTS client.
 * 5. The preview model is limited to the 01/02 families (`speech-02-hd` by
 *    default); `speech-2.8-hd`, which the app actually renders with, is not offered.
 *    So a clone-time preview is NOT a faithful sample of production output.
 *
 * !! RETENTION: A CLONE EXPIRES IN 7 DAYS UNLESS IT IS USED FOR TTS !!
 *
 * Fal's own docs for this endpoint: "To retain the voice permanently, use it with
 * a TTS (text-to-speech) endpoint at least once within 7 days. Otherwise, it will
 * be automatically deleted."
 *
 * So minting a voice is NOT the end of the job. Every caller owns pinning it:
 *
 * - Create path: a user who clones a voice and does not render within 7 days
 *   silently loses it. Pin at clone time rather than hoping they render in time.
 * - Backfill: pre-creating ~3.6k idle voices without pinning them would
 *   spend ~$5.4k on clones that mostly evaporate before anyone uses them. Each
 *   backfilled voice needs one TTS call to become permanent.
 *
 * The clone endpoint's inline preview is generated by the CLONE endpoint, not a
 * TTS endpoint, so do not assume it counts as the retaining call. Pin with a real
 * TTS request through `fal-minimax.ts` -- a few characters is enough, and at
 * $0.10/1k characters that call is effectively free next to the $1.50 clone it
 * protects.
 *
 * IMPORTANT: owns a PRIVATE fal client via `createFalClient` and must
 * never call `fal.config()`, which swaps the process-global singleton. Same
 * reasoning, and the same duplicated ~10 lines, as `fal-minimax.ts`
 * consolidates both into one shared helper.
 */
import { readFile } from 'node:fs/promises'
import { basename, extname } from 'node:path'

import { fal, type FalClient } from '@reelmakeeasy/llm'
import { minimaxVoiceCloneEndpoint } from '@reelmakeeasy/llm/adapters'
import { type ResolvedModel, resolveRole } from '@reelmakeeasy/llm/registry'

import { logger } from '../logger'
import { ensureError } from '../utils/error-handler'

/** Input for fal's hosted MiniMax voice-clone endpoint. */
type MinimaxVoiceCloneInput = Record<string, unknown>

/** The registry's voice-clone model. Throws when the role is disabled or not on fal. */
function resolveFalVoiceCloneModel(): ResolvedModel {
  const model = resolveRole('voice.clone')
  if (!model) {
    throw new Error('No model is configured for role voice.clone in reelmakeeasy.models.json')
  }
  if (model.provider !== 'fal') {
    throw new Error(`roles["voice.clone"] must be a fal model, got provider "${model.provider}"`)
  }
  return model
}

/**
 * Fal's clone endpoint accepts only these container formats (confirmed in a
 * pilot: a `.flac` upload was rejected), so callers transcode anything
 * else before coming here.
 */
export const FAL_CLONE_SUPPORTED_EXTENSIONS = ['.mp3', '.wav'] as const

/**
 * Client-side deadlines, matching `fal-minimax.ts`. Cloning is slower than
 * synthesis (upload plus training), so the subscribe budget is larger.
 */
const FAL_CLONE_SUBSCRIBE_TIMEOUT_MS = 600_000
const FAL_CLONE_DOWNLOAD_TIMEOUT_MS = 120_000

let cachedClient: FalClient | undefined

export interface FalVoiceCloneOptions {
  /**
   * Local path to the sample. Uploaded to fal storage to obtain the public URL
   * the endpoint requires. Mutually exclusive with `audioUrl`.
   */
  audioFile?: string
  /**
   * Already-public URL of the sample (e.g. a signed storage URL). Skips the upload.
   * Mutually exclusive with `audioFile`.
   */
  audioUrl?: string
  needNoiseReduction?: boolean
  needVolumeNormalization?: boolean
  /**
   * Text for the clone-time preview. A preview is generated ONLY when this is a
   * non-blank string; `null`, `undefined` and blank all skip it.
   *
   * Opt-in on purpose. Fal defaults this field and BILLS for the preview it then
   * generates, so leaving it unset would quietly spend money on audio nobody asked
   * for. The interactive create path passes real text (the user expects to hear the
   * new voice); the backfill passes nothing, because previews already
   * exist in storage.
   */
  previewText?: null | string
  userId: string
}

export interface FalVoiceCloneResult {
  message: string
  /** Preview audio, present only when `previewText` was a non-null string. */
  previewAudio?: Buffer
  status: 'error' | 'success'
  /**
   * Fal's own id for the cloned voice. Store as `voiceId` on a provider:'fal' row.
   *
   * NOT durable yet -- see the retention note in the module header. Fal deletes
   * this voice within 7 days unless it is used for TTS at least once.
   */
  voiceId?: string
}

function getFalClient(): FalClient {
  if (!cachedClient) {
    const credentials = process.env['FAL_KEY']
    if (!credentials) {
      throw new Error('FAL_KEY environment variable is required for fal-hosted voice cloning')
    }
    cachedClient = fal
  }
  return cachedClient
}

/** Test seam: drop the memoized client so a later call re-reads `FAL_KEY`. */
export function resetFalCloneClientForTesting(): void {
  cachedClient = undefined
}

/**
 * Clone a voice on fal's tenant.
 *
 * Never throws -- returns `{ status: 'error' }` so callers decide how to fail.
 */
export async function cloneVoice(options: FalVoiceCloneOptions): Promise<FalVoiceCloneResult> {
  try {
    const cloneModel = resolveFalVoiceCloneModel()
    const audioUrl = await resolveAudioUrl(options)
    const client = getFalClient()

    const input: MinimaxVoiceCloneInput = {
      audio_url: audioUrl,
      // fal spells this `noise_reduction`; MiniMax spells it `need_noise_reduction`.
      noise_reduction: options.needNoiseReduction ?? false,
      need_volume_normalization: options.needVolumeNormalization ?? false,
    }

    // Always send `text` explicitly. Omitting it is the one option that costs money
    // by accident: fal fills in its own default preview text and bills for the
    // resulting audio. So anything that is not a real request for a preview -- null,
    // undefined, or blank -- is sent as an explicit null, which skips generation.
    const wantsPreview =
      typeof options.previewText === 'string' && options.previewText.trim() !== ''
    input['text'] = wantsPreview ? options.previewText : null

    const result = await client.subscribe(minimaxVoiceCloneEndpoint(cloneModel), {
      // Registry `input` merges last so reelmakeeasy.models.json can override any field.
      input: { ...input, ...cloneModel.input },
      timeout: FAL_CLONE_SUBSCRIBE_TIMEOUT_MS,
    })
    const output = result.data as undefined | { audio?: { url?: string }; custom_voice_id?: string }
    const voiceId = output?.custom_voice_id

    if (!voiceId) {
      logger.warn(
        { requestId: result.requestId },
        '[FalMiniMaxClone] Clone returned no custom_voice_id',
      )
      return { message: 'Voice clone returned no voice id.', status: 'error' }
    }

    const previewUrl = output?.audio?.url
    const previewAudio = previewUrl ? await downloadPreview(previewUrl) : undefined

    logger.info(
      {
        requestId: result.requestId,
        userId: options.userId,
        voiceId,
        hasPreview: Boolean(previewAudio),
      },
      '[FalMiniMaxClone] Voice clone created',
    )

    return {
      message: `Voice clone "${voiceId}" created successfully.`,
      previewAudio,
      status: 'success',
      voiceId,
    }
  } catch (error) {
    const message = ensureError(error).message
    logger.error({ err: message, userId: options.userId }, '[FalMiniMaxClone] Voice clone failed')
    return { message, status: 'error' }
  }
}

/**
 * Fal needs a URL it can fetch. A local sample is uploaded to fal storage first;
 * an already-public URL is passed straight through.
 */
async function downloadPreview(url: string): Promise<Buffer | undefined> {
  try {
    const response = await fetch(url, {
      signal: AbortSignal.timeout(FAL_CLONE_DOWNLOAD_TIMEOUT_MS),
    })
    if (!response.ok) {
      throw new Error(`${response.status} ${response.statusText}`)
    }
    return Buffer.from(await response.arrayBuffer())
  } catch (error) {
    // A missing preview must not fail an otherwise successful clone: the voice
    // exists on fal's side and its id is what the caller actually needs.
    logger.warn(
      { err: ensureError(error).message },
      '[FalMiniMaxClone] Failed to download clone preview; continuing without it',
    )
    return undefined
  }
}

async function resolveAudioUrl(options: FalVoiceCloneOptions): Promise<string> {
  if (options.audioUrl && options.audioFile) {
    throw new Error('Provide exactly one of audioFile or audioUrl for fal voice cloning')
  }
  if (options.audioUrl) {
    return options.audioUrl
  }
  if (!options.audioFile) {
    throw new Error('Either audioFile or audioUrl is required for fal voice cloning')
  }

  const extension = extname(options.audioFile).toLowerCase()
  if (!(FAL_CLONE_SUPPORTED_EXTENSIONS as readonly string[]).includes(extension)) {
    throw new Error(
      `fal voice cloning accepts ${FAL_CLONE_SUPPORTED_EXTENSIONS.join('/')} only, got "${extension || 'no extension'}"`,
    )
  }

  const bytes = await readFile(options.audioFile)
  const contentType = extension === '.wav' ? 'audio/wav' : 'audio/mpeg'
  const file = new File([new Uint8Array(bytes)], basename(options.audioFile), {
    type: contentType,
  })
  return getFalClient().storage.upload(file)
}
