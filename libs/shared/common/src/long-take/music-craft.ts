/**
 * The user's music choice for a video, shared by the composer pill, the Easy card, the
 * agent tools and the storyboard. The bed itself is written by the BGM director from the
 * video's metadata; a choice here narrows it (a preset mood or the user's own words) or
 * turns it off.
 */
export type MusicChoice = 'auto' | 'calm' | 'off' | 'upbeat'

/** Where a project's bed comes from: made for the video, a library track, or the user's own. */
export type MusicSource = 'generated' | 'library' | 'upload'
export const MUSIC_SOURCES: readonly MusicSource[] = ['generated', 'library', 'upload']
/** A chosen track: a library track id or one of the user's uploaded tracks. */
export interface MusicTrackRef {
  id: string
  source: 'library' | 'upload'
}
/** What a surface asks for: a choice (mood / off), a typed wish, or a track. A track wins. */
export interface MusicRequest {
  choice?: MusicChoice
  note?: string
  track?: MusicTrackRef
}
/** The titles a text answer can name: the library and the user's own tracks. */
export interface MusicCatalog {
  library: { description?: string; id: string; mood?: string; title: string }[]
  mine: { aiGenerated?: boolean; durationSec?: number; id: string; name: string }[]
}
/** The music library's moods, in display order (browser-safe; the manifest reader validates against it). */
export const MUSIC_MOODS = ['lo-fi', 'chill', 'groove', 'piano'] as const
export type MusicMood = (typeof MUSIC_MOODS)[number]

/** Which videos a library track suits: calm ones or dynamic ones (the camera style). */
export type MusicTrackType = 'calm' | 'dynamic'
export const MUSIC_TRACK_TYPES: readonly MusicTrackType[] = ['calm', 'dynamic']

/**
 * The library track a video gets when the user picked none: one for calm videos, one for
 * dynamic ones (presets/music/library.json). Nothing is generated by default.
 */
export const DEFAULT_LIBRARY_TRACK: Record<MusicTrackType, string> = {
  calm: 'warm-lofi',
  dynamic: 'groovy-lofi',
}
export const MUSIC_LIBRARY_LABEL = 'From the library'
export const MUSIC_MINE_LABEL = 'My music'
export const MUSIC_TRACK_NAME_MAX_LENGTH = 80
export const MUSIC_TRACK_ID_MAX_LENGTH = 64

export const MUSIC_CHOICES: readonly MusicChoice[] = ['auto', 'upbeat', 'calm', 'off']
export const DEFAULT_MUSIC_CHOICE: MusicChoice = 'auto'
/** A typed wish is one line for the director, this long at most. */
export const MUSIC_NOTE_MAX_LENGTH = 200

export function sanitizeMusicChoice(value: unknown): MusicChoice {
  return MUSIC_CHOICES.includes(value as MusicChoice)
    ? (value as MusicChoice)
    : DEFAULT_MUSIC_CHOICE
}

export function sanitizeMusicSource(value: unknown): MusicSource | null {
  return MUSIC_SOURCES.includes(value as MusicSource) ? (value as MusicSource) : null
}

export const MUSIC_CHOICE_OPTIONS: Record<
  MusicChoice,
  { description: string; label: string; pill: string }
> = {
  auto: {
    description: "A library track that fits the video's style, under the narration.",
    label: 'Pick for me',
    pill: 'Auto',
  },
  calm: { description: 'Soft, slow and warm; stays out of the way.', label: 'Calm', pill: 'Calm' },
  off: { description: 'Narration only.', label: 'No music', pill: 'Off' },
  upbeat: {
    description: 'Energetic and driving, with a clear pulse.',
    label: 'Upbeat',
    pill: 'Upbeat',
  },
}

export const MUSIC_INFO =
  'Background music mixed under the narration: a track from the library (calm or dynamic, to fit the video), your own, or one made for this video when you describe it in your own words (about $0.01).'

/** What the director is told for a preset; nothing for Auto (it decides) and Off. */
export function musicNoteFor(choice: MusicChoice): null | string {
  if (choice === 'upbeat') return 'Upbeat: energetic, driving, positive, with a clear pulse.'
  if (choice === 'calm') return 'Calm: soft, slow, warm and sparse.'
  return null
}

function cleanNote(note: string | undefined): null | string {
  const oneLine = (note ?? '').replace(/\s+/g, ' ').trim()
  return oneLine ? oneLine.slice(0, MUSIC_NOTE_MAX_LENGTH) : null
}

/**
 * The project fields for a request: off; a chosen track; a bed made for the video when the
 * user typed a wish; otherwise the library's default track for the video's style (Calm and
 * Upbeat pick the calm and the dynamic one; Auto follows `cameraStyle`, calm when unknown).
 */
export function resolveMusicRequest(
  input: MusicRequest,
  opts: { cameraStyle?: MusicTrackType | null } = {},
): {
  bgmEnabled: boolean
  bgmNote: null | string
  bgmSource: MusicSource | null
  bgmTrackId: null | string
} {
  const choice = sanitizeMusicChoice(input.choice)
  if (choice === 'off')
    return { bgmEnabled: false, bgmNote: null, bgmSource: null, bgmTrackId: null }
  const track = sanitizeTrackRef(input.track)
  if (track)
    return { bgmEnabled: true, bgmNote: null, bgmSource: track.source, bgmTrackId: track.id }
  const note = cleanNote(input.note)
  if (note) return { bgmEnabled: true, bgmNote: note, bgmSource: 'generated', bgmTrackId: null }
  const type: MusicTrackType =
    choice === 'upbeat' || (choice === 'auto' && opts.cameraStyle === 'dynamic')
      ? 'dynamic'
      : 'calm'
  return {
    bgmEnabled: true,
    bgmNote: null,
    bgmSource: 'library',
    bgmTrackId: DEFAULT_LIBRARY_TRACK[type],
  }
}

function sanitizeTrackRef(ref: unknown): MusicTrackRef | null {
  const r = (ref ?? {}) as Partial<MusicTrackRef>
  if (r.source !== 'library' && r.source !== 'upload') return null
  const id = typeof r.id === 'string' ? r.id.trim().slice(0, MUSIC_TRACK_ID_MAX_LENGTH) : ''
  return id ? { id, source: r.source } : null
}

const normalizeTitle = (text: string) =>
  text
    .replace(/\s*\(recommended\)$/i, '')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()

/**
 * A track by name: a library title or one of the user's tracks, case-insensitive. An
 * exact match first; otherwise a substring (3+ characters) that fits exactly one track.
 * "my <name>" looks at the user's tracks first; otherwise the library comes first.
 */
export function findMusicTrack(text: string, catalog: MusicCatalog): MusicTrackRef | null {
  const raw = normalizeTitle(text)
  const mineFirst = /^my\s+/.test(raw)
  const q = raw.replace(/^my\s+/, '')
  if (!q) return null
  const mine = catalog.mine.map((t) => ({
    ai: t.aiGenerated === true,
    key: normalizeTitle(t.name),
    ref: { id: t.id, source: 'upload' as const },
  }))
  const library = catalog.library.map((t) => ({
    ai: false,
    key: normalizeTitle(t.title),
    ref: { id: t.id, source: 'library' as const },
  }))
  const ordered = mineFirst ? [...mine, ...library] : [...library, ...mine]
  const exact = ordered.find((e) => e.key === q)
  if (exact) return exact.ref
  if (q.length < 3) return null
  // AI track names are made of everyday music words ("Curious Acoustic Echo"): only their
  // full name picks them, so a typed wish like "acoustic" still makes a new bed.
  const partial = ordered.filter((e) => !e.ai && e.key.includes(q))
  return partial.length === 1 ? partial[0].ref : null
}

/** Refusals, so a user who declines music never pays for a bed: a bare "no"/"none"/"off", or
 *  anything that starts with "no music", "none", "nothing" or "without music". */
const NO_MUSIC_RE =
  /^(no|none|nothing|off|skip|no thanks|no thank you)[.!]?$|^(no music|without music|none|nothing)\b/

/** A track named exactly like the text (a library title or one of the user's tracks). */
export function musicRequestFromText(text?: string, catalog?: MusicCatalog): MusicRequest {
  const wish = (text ?? '').trim()
  const lower = normalizeTitle(wish)
  if (!wish || lower === 'auto') return { choice: 'auto' }
  if (MUSIC_CHOICES.includes(lower as MusicChoice)) return { choice: lower as MusicChoice }
  const byLabel = MUSIC_CHOICES.find((c) => MUSIC_CHOICE_OPTIONS[c].label.toLowerCase() === lower)
  if (byLabel) return { choice: byLabel }
  // A track's exact name wins over a refusal ("Nothing But Sky" is a track, not "no").
  const named = catalog ? exactMusicTrack(wish, catalog) : null
  if (named) return { choice: 'auto', track: named }
  if (NO_MUSIC_RE.test(lower)) return { choice: 'off' }
  const track = catalog ? findMusicTrack(wish, catalog) : null
  if (track) return { choice: 'auto', track }
  return { choice: 'auto', note: wish }
}

function exactMusicTrack(text: string, catalog: MusicCatalog): MusicTrackRef | null {
  const q = normalizeTitle(text).replace(/^my\s+/, '')
  const hit =
    catalog.mine.find((t) => normalizeTitle(t.name) === q) ??
    catalog.library.find((t) => normalizeTitle(t.title) === q)
  if (!hit) return null
  return 'title' in hit ? { id: hit.id, source: 'library' } : { id: hit.id, source: 'upload' }
}

/** A track's title in the catalog (a library title or the user's name for it), if known. */
export function musicTrackTitle(ref: MusicTrackRef, catalog?: MusicCatalog): null | string {
  if (!catalog) return null
  const title =
    ref.source === 'library'
      ? catalog.library.find((t) => t.id === ref.id)?.title
      : catalog.mine.find((t) => t.id === ref.id)?.name
  return title ?? null
}

/** The pill text for a request: the track's title when it is known, else the choice. */
export function musicRequestLabel(req: MusicRequest, catalog?: MusicCatalog): string {
  const choice = sanitizeMusicChoice(req.choice)
  const title = choice !== 'off' && req.track ? musicTrackTitle(req.track, catalog) : null
  return title ?? MUSIC_CHOICE_OPTIONS[choice].pill
}

/**
 * A stored request (the composer remembers it between videos): an object as written, or a
 * bare choice string from before tracks existed. Unknown values read as Auto.
 */
export function sanitizeMusicRequest(value: unknown): MusicRequest {
  if (typeof value === 'string') return { choice: sanitizeMusicChoice(value) }
  const raw = (value ?? {}) as Partial<MusicRequest>
  const note = cleanNote(typeof raw.note === 'string' ? raw.note : undefined)
  const track = sanitizeTrackRef(raw.track)
  return {
    choice: sanitizeMusicChoice(raw.choice),
    ...(note ? { note } : {}),
    ...(track ? { track } : {}),
  }
}
