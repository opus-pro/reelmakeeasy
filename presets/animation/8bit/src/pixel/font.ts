const CELLS = {}
for (const [k, rows] of Object.entries(G)) {
  const cells = []
  rows.forEach((r, y) => [...r].forEach((c, x) => c === '#' && cells.push([x, y])))
  CELLS[k] = cells
}
export const GLYPH_W = 6, GLYPH_H = 7 // 5 cells plus 1 cell of spacing
export const textWidth = (s, u) => [...String(s)].length * GLYPH_W * u - u
// Draws text with its top-left at (x, y); u is the size of one font cell in px.
export function drawText(g, s, x, y, u, color) {
  g.fillStyle = color
  let cx = Math.round(x)
  for (const ch of String(s).toUpperCase()) {
    const cells = CELLS[ch] || CELLS['?']
    for (const [px, py] of cells) g.fillRect(cx + px * u, Math.round(y) + py * u, u, u)
    cx += GLYPH_W * u
  }
}
